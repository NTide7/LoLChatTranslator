    public static string T(string language, string key)
    {
        var normalized = NormalizeLanguage(language);
        if (Texts.TryGetValue(normalized, out var table) && table.TryGetValue(key, out var value))
        {
            return value;
        }

        return Texts["zh-Hans"].TryGetValue(key, out var fallback) ? fallback : key;
    }

    public static string LanguageName(string uiLanguage, string languageCode)
    {
        return languageCode switch
        {
            "auto" => T(uiLanguage, "AutoDetect"),
            "zh-Hans" or "zh-CN" or "zh" => "简体中文",
            "zh-Hant" or "zh-TW" or "zh-HK" => "繁體中文",
            "en" => "English",
            "ko" => "한국어",
            "ja" => "日本語",
            "vi" => "Tiếng Việt",
            _ => languageCode
        };
    }

    public static string LocalizedLanguageName(string uiLanguage, string languageCode)
    {
        return languageCode switch
        {
            "auto" => T(uiLanguage, "AutoDetect"),
            "zh-Hans" or "zh-CN" or "zh" => T(uiLanguage, "Chinese"),
            "zh-Hant" or "zh-TW" or "zh-HK" => T(uiLanguage, "TraditionalChinese"),
            "en" => T(uiLanguage, "English"),
            "ko" => T(uiLanguage, "Korean"),
            "ja" => T(uiLanguage, "Japanese"),
            "vi" => T(uiLanguage, "Vietnamese"),
            _ => languageCode
        };
    }

    public static string NormalizeLanguage(string? language)
    {
        if (string.IsNullOrWhiteSpace(language))
        {
            return "zh-Hans";
        }

        if (language.Equals("zh", StringComparison.OrdinalIgnoreCase)
            || language.Equals("zh-CN", StringComparison.OrdinalIgnoreCase))
        {
            return "zh-Hans";
        }

        if (language.Equals("zh-TW", StringComparison.OrdinalIgnoreCase)
            || language.Equals("zh-HK", StringComparison.OrdinalIgnoreCase))
        {
            return "zh-Hant";
        }

        return SupportedUiLanguages.Contains(language, StringComparer.OrdinalIgnoreCase)
            ? language
            : "zh-Hans";
    }
